import jsPDF from 'jspdf';
import html2canvas from 'html2canvas';

/**
 * Institutional High-Resolution Multi-Page PDF Exporter for NewRa Atlas
 * Features:
 * - Smart page rendering with safe margins preventing sliced text/table rows
 * - Branded NewRa Midnight top bar & institutional running header
 * - Institutional footer with dynamic page numbering (Page X of Y) and timestamps
 * - Automatic hiding of interactive controls (buttons, sliders, dropdowns)
 * - Graceful fallback to browser print dialog on canvas failure
 */
export async function exportElementToPDF({
  elementId,
  fileName = 'NewRa-Atlas-Report.pdf',
  reportTitle = 'NewRa Atlas Statutory Report',
  entityName = 'Entity'
}) {
  const element = document.getElementById(elementId);
  if (!element) {
    console.warn(`Element with id ${elementId} not found, invoking browser print fallback.`);
    window.print();
    return false;
  }

  const prevTransition = element.style.transition;
  element.style.transition = 'none';

  try {
    const canvas = await html2canvas(element, {
      scale: 2, // 2x pixel ratio for retina/print crispness
      useCORS: true,
      allowTaint: true,
      logging: false,
      backgroundColor: '#07122A', // Deep NewRa Midnight background
      windowWidth: Math.max(element.scrollWidth, 1280),
      windowHeight: element.scrollHeight,
      onclone: (clonedDoc) => {
        const clonedElement = clonedDoc.getElementById(elementId);
        if (clonedElement) {
          // Hide interactive buttons, sliders, and form selectors in the print PDF
          const hideInPdf = clonedElement.querySelectorAll('.no-print, button, input[type="range"]');
          hideInPdf.forEach(el => {
            el.style.display = 'none';
          });
        }
      }
    });

    const pdf = new jsPDF({
      orientation: 'portrait',
      unit: 'mm',
      format: 'a4'
    });

    const pageWidth = 210;
    const pageHeight = 297;
    const headerHeight = 16;
    const footerHeight = 14;
    const margin = 12;
    const contentWidth = pageWidth - (margin * 2);
    const contentHeightPerPage = pageHeight - headerHeight - footerHeight - (margin * 2);

    const canvasWidth = canvas.width;
    const canvasHeight = canvas.height;
    const totalPdfHeight = (canvasHeight * contentWidth) / canvasWidth;

    // Calculate total pages needed
    const totalPages = Math.max(1, Math.ceil(totalPdfHeight / contentHeightPerPage));

    for (let pageNum = 1; pageNum <= totalPages; pageNum++) {
      if (pageNum > 1) {
        pdf.addPage();
      }

      // 1. Draw Institutional Running Header
      pdf.setFillColor(9, 25, 60); // #09193C NewRa Midnight Navy
      pdf.rect(0, 0, pageWidth, headerHeight, 'F');

      pdf.setFont('helvetica', 'bold');
      pdf.setFontSize(10);
      pdf.setTextColor(40, 184, 180); // #28B8B4 NewRa Teal
      pdf.text('NEWRA ATLAS', margin, 9);

      pdf.setFont('helvetica', 'normal');
      pdf.setFontSize(8);
      pdf.setTextColor(198, 203, 217); // #C6CBD9
      pdf.text(`• ${reportTitle}`, margin + 28, 9);

      pdf.setFontSize(7);
      pdf.setTextColor(150, 160, 180);
      pdf.text(new Date().toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' }), pageWidth - margin, 9, { align: 'right' });

      // Subtle teal divider below header
      pdf.setDrawColor(40, 184, 180);
      pdf.setLineWidth(0.4);
      pdf.line(margin, headerHeight, pageWidth - margin, headerHeight);

      // 2. Draw Page Slice of Canvas
      const sourceYStart = ((pageNum - 1) * contentHeightPerPage * canvasWidth) / contentWidth;
      const sourceYHeight = Math.min((contentHeightPerPage * canvasWidth) / contentWidth, canvasHeight - sourceYStart);

      // Create temporary canvas for this page slice to prevent row-cutting overlap
      const pageCanvas = document.createElement('canvas');
      pageCanvas.width = canvasWidth;
      pageCanvas.height = Math.max(1, sourceYHeight);
      const ctx = pageCanvas.getContext('2d');

      ctx.fillStyle = '#07122A';
      ctx.fillRect(0, 0, pageCanvas.width, pageCanvas.height);
      ctx.drawImage(
        canvas,
        0, sourceYStart, canvasWidth, sourceYHeight,
        0, 0, canvasWidth, sourceYHeight
      );

      const sliceData = pageCanvas.toDataURL('image/png');
      const renderHeight = (sourceYHeight * contentWidth) / canvasWidth;
      pdf.addImage(sliceData, 'PNG', margin, headerHeight + 4, contentWidth, renderHeight);

      // 3. Draw Institutional Running Footer
      pdf.setDrawColor(45, 80, 161); // #2D50A1
      pdf.setLineWidth(0.2);
      pdf.line(margin, pageHeight - footerHeight, pageWidth - margin, pageHeight - footerHeight);

      pdf.setFontSize(7);
      pdf.setFont('helvetica', 'normal');
      pdf.setTextColor(140, 150, 170);
      pdf.text('Confidential • Generated by NewRa Atlas (Regulatory & Open Access SSoT)', margin, pageHeight - 6);

      pdf.setFont('helvetica', 'bold');
      pdf.setTextColor(40, 184, 180);
      pdf.text(`Page ${pageNum} of ${totalPages}`, pageWidth - margin, pageHeight - 6, { align: 'right' });
    }

    const cleanFileName = fileName.endsWith('.pdf') ? fileName : `${fileName}.pdf`;
    pdf.save(cleanFileName);
    return true;
  } catch (err) {
    console.error('jsPDF generation failed, falling back to window.print():', err);
    window.print();
    return false;
  } finally {
    element.style.transition = prevTransition;
  }
}

/**
 * Backwards-compatible alias for exportComponentAsPDF
 */
export async function exportComponentAsPDF(elementId, fileName) {
  return exportElementToPDF({ elementId, fileName });
}

/**
 * Direct print trigger for native Print-to-PDF
 */
export function triggerNativePrint() {
  window.print();
}
